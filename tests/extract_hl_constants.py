#!/usr/bin/env python3
"""regenerates tests/hl_constants.lua from a hyprland source checkout. re-run it when moving to a
new hyprland and diff the result.

    python3 tests/extract_hl_constants.py /path/to/Hyprland [--out tests/hl_constants.lua]
"""
import re
import sys
from pathlib import Path

if len(sys.argv) < 2:
    sys.exit(__doc__)
root = Path(sys.argv[1])
out = Path(sys.argv[sys.argv.index("--out") + 1]) if "--out" in sys.argv else Path(__file__).with_name("hl_constants.lua")
version = (root / "VERSION").read_text().strip()


def lua_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


src = (root / "src/config/values/ConfigValues.cpp").read_text()
chunks = re.split(r"(?=MS<\w+>\()", src)
config = []
for ch in chunks:
    m = re.match(r'MS<(\w+)>\(\s*"([^"]+)"', ch)
    if not m:
        continue
    typ, name = m.group(1), m.group(2)
    mn = re.search(r"\.min\s*=\s*(-?[0-9.]+)", ch)
    mx = re.search(r"\.max\s*=\s*(-?[0-9.]+)", ch)
    choices = re.search(r"strChoice\(\{([^}]*)\}", ch)
    omap = None
    mi = ch.find("OptionMap{")
    if mi >= 0:
        depth, j = 0, mi + len("OptionMap")
        for j in range(mi + len("OptionMap"), len(ch)):
            depth += (ch[j] == "{") - (ch[j] == "}")
            if depth == 0:
                break
        omap = ch[mi + len("OptionMap") + 1:j]
    entry = {"type": typ}
    if mn:
        entry["min"] = float(mn.group(1))
    if mx:
        entry["max"] = float(mx.group(1))
    if choices:
        entry["choices"] = re.findall(r'"([^"]*)"', choices.group(1))
    if omap:
        entry["map"] = re.findall(r'\{\s*"([^"]+)"\s*,', omap)
    # "input:touchpad:tap-to-click" -> input.touchpad.tap_to_click, like luaConfigValueName
    config.append((name.replace(":", ".").replace("-", "_"), entry))
assert len(config) > 300, f"suspiciously few config values: {len(config)}"

hpp = (root / "src/config/lua/bindings/LuaBindingsInternal.hpp").read_text()
effects = re.findall(r'\{"([a-z_0-9]+)",\s*\[\]\(\)\s*->\s*ILuaConfigValue\*\s*\{\s*return new CLuaConfig(\w+)', hpp)
assert len(effects) > 40, f"suspiciously few window effects: {len(effects)}"

tree = (root / "src/config/shared/animation/AnimationTree.cpp").read_text()
leaves = sorted(set(re.findall(r'"([a-zA-Z]+)"', tree)))
leaves = [l for l in leaves if l[0].islower() and l not in ('default', 'linear')]  # those two are curve names

disp = (root / "src/config/lua/bindings/LuaBindingsDispatchers.cpp").read_text()
i = disp.index('Internal::setFn(L, "move_to_corner"')
j = disp.index('lua_setfield(L, -2, "dsp")')
block = disp[i - 600:j]
dsp = {"": []}
ns_stack = ""
for line in block.splitlines():
    m = re.search(r'setFn\(L,\s*"(\w+)"', line)
    if m:
        dsp.setdefault("__pending", []).append(m.group(1))
        continue
    m = re.search(r'lua_setfield\(L,\s*-2,\s*"(\w+)"\)', line)
    if m:
        ns = m.group(1)
        dsp[ns] = dsp.pop("__pending", [])
dsp[""] = dsp.pop("__pending", [])
dsp.pop("dsp", None)

top = (root / "src/config/lua/bindings/LuaBindingsToplevel.cpp").read_text()
k = top.index("static int hlBind(")
bind_block = top[k:top.index("\nstatic int ", k + 10)]
bind_opts = sorted(set(re.findall(r'"([a-z_]+)"', bind_block)) - {"__lua", "list"} | {"mouse"})  # `mouse`: used by example/hyprland.lua

o = ["-- GENERATED by tests/extract_hl_constants.py from the Hyprland source. DO NOT EDIT.",
     f"-- Source: hyprwm/Hyprland tag v{version}",
     "return {", f'  version = {lua_str(version)},', "", "  config = {"]
for name, e in config:
    parts = [f'type = {lua_str(e["type"])}']
    for key in ("min", "max"):
        if key in e:
            parts.append(f"{key} = {e[key]:g}")
    if "choices" in e:
        parts.append("choices = { " + ", ".join(lua_str(c) for c in e["choices"]) + " }")
    if "map" in e:
        parts.append("map = { " + ", ".join(lua_str(c) for c in e["map"]) + " }")
    o.append(f"    [{lua_str(name)}] = {{ {', '.join(parts)} }},")
o.append("  },")
o.append("")
o.append("  window_effects = {")
for n, t in effects:
    o.append(f"    {n} = {lua_str(t)},")
o.append("  },")
o.append("")
o.append("  window_match_keys = { " + ", ".join(lua_str(x) for x in
         ["class", "content", "float", "focus", "fullscreen", "fullscreen_state_client", "fullscreen_state_internal",
          "group", "initial_class", "initial_title", "modal", "namespace", "pin", "tag", "title", "workspace",
          "xdg_tag", "xwayland"]) + " },")
o.append("  layer_match_keys = { \"namespace\" },")
o.append("  layer_effects = { no_anim = \"bool\", blur = \"bool\", blur_popups = \"bool\", ignore_alpha = \"float01\", "
         "dim_around = \"bool\", xray = \"bool\", animation = \"string\", order = \"int\", above_lock = \"int02\", "
         "no_screen_share = \"bool\" },")
o.append("  animation_leaves = { " + ", ".join(lua_str(x) for x in leaves) + " },")
o.append("  bind_options = { " + ", ".join(lua_str(x) for x in bind_opts) + " },")
o.append("  dsp = {")
for ns, names in dsp.items():
    key = f"[{lua_str(ns)}]" if ns == "" else ns
    o.append(f"    {key if ns else '_root'} = {{ " + ", ".join(lua_str(x) for x in names) + " },")
o.append("  },")
o.append("}")
out.write_text("\n".join(o) + "\n")
print(f"wrote {out}: {len(config)} config values, {len(effects)} window effects, {len(leaves)} animation leaves, "
      f"{sum(len(v) for v in dsp.values())} dispatchers, bind options: {bind_opts}")
